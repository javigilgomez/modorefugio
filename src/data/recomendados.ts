/** Líneas que son solo acciones de revisión y no deben llevar enlaces. */
const SKIP_ALL: RegExp[] = [
  /roles asignados/i,
  /revisa linternas y pilas/i,
  /cuenta el agua embotellada/i,
  /revisa el botiqu[ií]n y las caducidades/i,
];

const BY_ID = Object.fromEntries(RECOMENDADOS.map((r) => [r.id, r]));

export function findRecs(text: string): Rec[] {
  const plain = text.replace(/<[^>]+>/g, '');
  if (SKIP_ALL.some((re) => re.test(plain))) return [];
  const out: { rec: Rec; idx: number }[] = [];
  const seen = new Set<string>();
  for (const rule of REC_RULES) {
    if (seen.has(rule.id)) continue;
    if (rule.exclude?.some((re) => re.test(plain))) continue;
    let idx = -1;
    for (const re of rule.include) {
      const i = plain.search(re);
      if (i >= 0 && (idx < 0 || i < idx)) idx = i;
    }
    if (idx < 0) continue;
    const rec = BY_ID[rule.id];
    if (!rec) continue;
    seen.add(rule.id);
    out.push({ rec, idx });
  }
  return out.sort((a, b) => a.idx - b.idx).map((x) => x.rec);
}

/** Primer producto que coincide (plantillas que solo muestran un «Recomendado»). */
export function findRec(text: string): Rec | undefined {
  return findRecs(text)[0];
}

